/* Ближайшие станции к точке: [{ name, line, dist, time, mode, label }] */
function metroNearby(lat, lon, limit) {
  const R = 6371000, rad = Math.PI / 180;
  const out = METRO_SPB.map(function (s) {
    const dLat = (s[2] - lat) * rad;
    const dLon = (s[3] - lon) * rad * Math.cos((lat + s[2]) / 2 * rad);
    const dist = Math.round(Math.sqrt(dLat * dLat + dLon * dLon) * R);
    /* 1.35 — поправка на то, что по улицам дорога длиннее прямой */
    const road = dist * 1.35;
    /* пешком 5 км/ч; дальше 20 минут ходу считаем время на транспорте (20 км/ч) */
    const walk = Math.max(1, Math.round(road / 83));
    const drive = Math.max(1, Math.round(road / 333));
    const onFoot = walk <= 20;
    return {
      name: s[0],
      line: s[1],
      dist: dist,
      time: onFoot ? walk : drive,
      mode: onFoot ? 'пешком' : 'на транспорте',
      label: (onFoot ? walk : drive) + ' мин ' + (onFoot ? 'пешком' : 'на транспорте')
    };
  });
  out.sort(function (a, b) { return a.dist - b.dist; });
  return out.slice(0, limit || 5);
}
